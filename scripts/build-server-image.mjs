#!/usr/bin/env node
/**
 * Build a pre-baked, sandbox-ready container image for an MCP server.
 *
 * The package is installed at BUILD time, so at run time the gateway can launch
 * it with `--network none` — no npx/uvx fetch needed. This is the strongest
 * isolation for untrusted servers: no runtime network at all.
 *
 * Usage:
 *   node scripts/build-server-image.mjs --slug <slug> --package <npm-pkg> [--runtime node|python]
 *
 * Examples:
 *   node scripts/build-server-image.mjs \
 *     --slug npx-modelcontextprotocol-server-everything \
 *     --package @modelcontextprotocol/server-everything
 *
 *   node scripts/build-server-image.mjs \
 *     --slug some-python-server --package some-mcp-pkg --runtime python
 *
 * The resulting image is tagged `mcp-sandbox/<slug>:latest` — the same name
 * the gateway looks up via resolveBakedImage(), so it's used automatically on
 * the next connection.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

const slug = arg("slug");
const pkg = arg("package");
const runtime = arg("runtime", "node");

if (!slug || !pkg) {
  console.error("Error: --slug and --package are required.");
  console.error(
    "Usage: node scripts/build-server-image.mjs --slug <slug> --package <pkg> [--runtime node|python]",
  );
  process.exit(1);
}

const safeSlug = slug.replace(/[^a-z0-9_.-]/gi, "-").toLowerCase();
const imageTag = `mcp-sandbox/${safeSlug}:latest`;

// Build the Dockerfile. The package is installed globally so it resolves
// offline at runtime. HOME/cache point at /tmp (the runtime tmpfs).
const dockerfile =
  runtime === "python"
    ? `# Auto-generated by build-server-image.mjs
FROM python:3.12-slim
RUN pip install --no-cache-dir uv && uv tool install ${shellEscape(pkg)}
ENV HOME=/tmp
ENV UV_CACHE_DIR=/tmp/.uv
USER 1000:1000
`
    : `# Auto-generated by build-server-image.mjs
FROM node:22-alpine
RUN npm install -g ${shellEscape(pkg)}
ENV HOME=/tmp
ENV npm_config_cache=/tmp/.npm
USER node
`;

function shellEscape(s) {
  // Basic guard against injection in the package name.
  if (!/^[@a-z0-9._/-]+$/i.test(s)) {
    console.error(`Refusing to build: suspicious package name "${s}"`);
    process.exit(1);
  }
  return s;
}

/**
 * Detect the executable (bin) name a package installs. The gateway runs this
 * directly at runtime (offline) instead of npx, which doesn't resolve globally
 * installed scoped packages.
 */
function detectBinName(pkg, runtime) {
  if (runtime === "python") {
    // uv tool installs a console script named after the package by convention.
    return pkg.replace(/[^a-z0-9_-]/gi, "-").toLowerCase();
  }
  try {
    // npm is a shell script (.cmd on Windows) — needs shell:true to invoke.
    // pkg is validated by shellEscape() before this point.
    const out = execFileSync("npm", ["view", pkg, "bin", "--json"], {
      encoding: "utf-8",
      shell: true,
    }).trim();
    if (!out) return null;
    const bin = JSON.parse(out);
    if (typeof bin === "string") return null; // unusual shape
    const names = Object.keys(bin);
    return names[0] ?? null;
  } catch {
    return null;
  }
}

const binName = detectBinName(pkg, runtime);

const buildDir = mkdtempSync(join(tmpdir(), "mcp-image-"));
const dockerfilePath = join(buildDir, "Dockerfile");
writeFileSync(dockerfilePath, dockerfile, "utf-8");

console.log(`Building pre-baked image: ${imageTag}`);
console.log(`  package: ${pkg}`);
console.log(`  runtime: ${runtime}`);
console.log(`  bin:     ${binName ?? "(not detected — will fall back to npx)"}`);
console.log("");

// Label the image with the bin name so the gateway runs it directly offline.
const buildArgs = ["build", "-f", dockerfilePath, "-t", imageTag];
if (binName) buildArgs.push("--label", `mcp.sandbox.bin=${binName}`);
buildArgs.push(buildDir);

try {
  execFileSync("docker", buildArgs, { stdio: "inherit" });
  console.log("");
  console.log(`✅ Built ${imageTag}`);
  console.log(
    `The gateway will use this image automatically for slug "${slug}" (network:none works offline).`,
  );
} catch (err) {
  console.error(`❌ Build failed: ${err instanceof Error ? err.message : err}`);
  process.exit(1);
} finally {
  rmSync(buildDir, { recursive: true, force: true });
}
